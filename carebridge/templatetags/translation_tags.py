@register.simple_tag(takes_context=True)
def t(context, text):
    """Translate text based on current language setting."""
    site_lang = context.get("site_lang")
    if not site_lang:
        request = context.get("request")
        if request:
            site_lang = request.session.get("site_lang")
    if not site_lang:
        try:
            from django.utils.translation import get_language
            current = get_language()
            if current and current.startswith("bn"):
                site_lang = "bn"
        except Exception:
            pass

    if site_lang == "bn":
        translated = TRANSLATIONS.get("bn", {}).get(text)
        if translated:
            return translated
    return text


@register.simple_tag(takes_context=True)
def translate_bn(context, text):
    """Alias for t tag - translate to Bangla if current language is Bangla."""
    return t(context, text)
